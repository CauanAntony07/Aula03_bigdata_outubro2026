num_01 = float(input('digite o primeiro numero: '))
num_02 = float(input('digite o segundo numero: '))

soma = num_01 + num_02
sub = num_01 - num_02
div = num_01 / num_02
mult = num_01 * num_02

print(f'soma: {soma:.2f}')
print(f'subtração: {sub:.2f}')
print(f'divisão: {div:.2f}')
print(f'multiplicação: {mult:.2f}')
